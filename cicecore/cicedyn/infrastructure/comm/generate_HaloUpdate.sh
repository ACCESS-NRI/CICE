 subroutine ice_HaloUpdate_multi(halo, fieldLoc, fieldKind,      &
                                 array1, array2, array3, array4, &
                                 array5, array6, fillValue)

!  Generated by ./generate_HaloUpdate.sh on ${cdate}
!  ice_HaloUpdate_multi is generated separately from the main template;
!  keep it consistent with the 3d routines (it is the 3d routine with the
!  3rd dimension replaced by a list of arrays, and a per-array tripole fold).

!  Halo update for up to six 2d double precision arrays in one round of
!  messages (one message per neighbour task).  Each array has its own
!  field location and kind, so fields on different grids (e.g. the Eface
!  and Nface velocities of the C-grid) can share one exchange.  Values
!  are packed straight from the arrays; no stack/unstack copies.
!
!  This is ice_HaloUpdate3DR8 with the third dimension replaced by the
!  list of arrays.  Each array is processed exactly as ice_HaloUpdate2DR8
!  processes it on its own, so results are bitwise identical to calling
!  ice_HaloUpdate once per array.  Only the aggregation of the messages
!  differs.  fieldLoc(n) and fieldKind(n) describe arrayn.  Arrays must
!  be distinct (no aliasing).

   type (ice_halo), intent(in) :: &
      halo                 ! precomputed halo structure containing all
                           !  information needed for halo update

   integer (int_kind), dimension(:), intent(in) :: &
      fieldLoc,           &! id for location on horizontal grid, per array
                           !  (center, NEcorner, Nface, Eface)
      fieldKind            ! id for type of field, per array
                           !  (scalar, vector, angle)

   real (dbl_kind), dimension(:,:,:), intent(inout), target :: &
      array1               ! first array to update

   real (dbl_kind), dimension(:,:,:), intent(inout), target, optional :: &
      array2, array3, array4, array5, array6   ! further arrays to update

   real (dbl_kind), intent(in), optional :: &
      fillValue            ! optional value to put in ghost cells
                           !  where neighbor points are unknown
                           !  (e.g. eliminated land blocks or
                           !   closed boundaries)

!-----------------------------------------------------------------------
!
!  local variables
!
!-----------------------------------------------------------------------

   integer (int_kind) ::           &
      i,j,k,l,n,nmsg,     &! dummy loop indices
      ilo,ihi,jlo,jhi,    &! block sizes for fill
      iblk,iblock,jblock, &! global block indices
      istat,              &! allocate status flag
      nxGlobal,           &! global domain size in x (tripole)
      nz, nt,             &! size of array in 3rd,4th dimensions
      iSrc,jSrc,          &! source addresses for message
      iDst,jDst,          &! dest   addresses for message
      srcBlock,           &! local block number for source
      dstBlock,           &! local block number for destination
      iSrc0, jSrc0         ! tripole buffer addresses before offsets

   real (dbl_kind) :: &
      fill,               &! value to use for unknown points
      x1,x2,xavg           ! scalars for enforcing symmetry at U pts

   logical (log_kind) :: &
      ewfillouter,        &! fill outer boundary ew
      nsfillouter,        &! fill outer boundary ns
      ltripoleOnly,       &! local flag to execute halo only across tripole seam (always off)
      ltripole             ! this task copies values out of the tripole buffer

   real (dbl_kind), dimension(:,:,:,:), allocatable :: &
      bufTripole           ! 4d tripole buffer

#ifndef NO_MPI
   integer (int_kind) :: &
      ierr,               &! error or status flag for MPI,alloc
      len                  ! length of message

   integer (int_kind), dimension(:), allocatable :: &
      sndRequest,         &! MPI request ids
      rcvRequest           ! MPI request ids

   integer (int_kind), dimension(:,:), allocatable :: &
      sndStatus,          &! MPI status flags
      rcvStatus            ! MPI status flags

   real (dbl_kind), dimension(:,:), allocatable :: &
      bufSend, bufRecv     ! 4d send,recv buffers
#endif

   integer (int_kind), parameter :: &
      maxfld = 6           ! maximum number of arrays per call

   type :: r8ptr3d
      real (dbl_kind), dimension(:,:,:), pointer :: p
   end type

   type (r8ptr3d), dimension(maxfld) :: &
      fld                  ! arrays being updated

   integer (int_kind), dimension(maxfld) :: &
      floc, fkind,        &! location and kind of each array updated
      isign,              &! sign factor for tripole grids, per array
      ioffset, joffset     ! address shifts for tripole, per array

   integer (int_kind) :: &
      nfld                 ! number of arrays being updated

   character(len=*), parameter :: subname = '(ice_HaloUpdate_multi)'

!-----------------------------------------------------------------------
!
!  abort or return on unknown or noupdate field_loc or field_type
!
!-----------------------------------------------------------------------

   nfld = 0
   call add_field(1, array1)
   if (present(array2)) call add_field(2, array2)
   if (present(array3)) call add_field(3, array3)
   if (present(array4)) call add_field(4, array4)
   if (present(array5)) call add_field(5, array5)
   if (present(array6)) call add_field(6, array6)

   if (nfld == 0) return

!-----------------------------------------------------------------------
!
!  initialize error code and fill value
!
!-----------------------------------------------------------------------

   ewfillouter = .true.
   nsfillouter = .true.

   ! do not fill outer boundary if open or closed
   if (halo%ewBoundaryType == 'open' .or. &
       halo%ewBoundaryType == 'closed') ewfillouter=.false.
   if (halo%nsBoundaryType == 'open' .or. &
       halo%nsBoundaryType == 'closed') nsfillouter=.false.

   if (present(fillValue)) then
      fill = fillValue
      ! always fill outer boundary if fillValue is passed
      ewfillouter = .true.
      nsfillouter = .true.
   else
      fill = 0._dbl_kind
   endif

   ltripoleOnly = .false.

   nz = nfld
   nt = 1

   !*** the tripole buffer is only read back through local copies with
   !*** srcBlock < 0; tasks without such copies skip all tripole work
   ltripole = .false.
   if (nxGlobal_size > 0) then
      do nmsg=1,halo%numLocalCopies
         if (halo%srcLocalAddr(3,nmsg) < 0) then
            ltripole = .true.
            exit
         endif
      end do
   endif

   nxGlobal = 0
   if (ltripole) then
      nxGlobal = nxGlobal_size
      allocate(bufTripole(nxGlobal,halo%tripoleRows,nz,nt),stat=istat)
      if (istat > 0) then
         call abort_ice(subname//'ERROR: allocating bufTripole array')
         return
      endif
      bufTripole = fill
   endif

#ifndef NO_MPI
!-----------------------------------------------------------------------
!
!  allocate request and status arrays for messages
!  allocate send/recv buffers
!
!-----------------------------------------------------------------------

   allocate(sndRequest(halo%numMsgSend), &
            rcvRequest(halo%numMsgRecv), &
            sndStatus(MPI_STATUS_SIZE,halo%numMsgSend), &
            rcvStatus(MPI_STATUS_SIZE,halo%numMsgRecv), stat=istat)

   if (istat > 0) then
      call abort_ice(subname//'ERROR: allocating req,status arrays')
      return
   endif

   allocate(bufSend(bufSizeSend*nz*nt, halo%numMsgSend),   &
            bufRecv(bufSizeRecv*nz*nt, halo%numMsgRecv),   &
            stat=istat)

   if (istat > 0) then
      call abort_ice(subname//'ERROR: allocating buf arrays')
      return
   endif

!-----------------------------------------------------------------------
!
!  post receives
!
!-----------------------------------------------------------------------

   do nmsg=1,halo%numMsgRecv
      len = halo%SizeRecv(nmsg)*nz*nt
      call MPI_IRECV(bufRecv(1,nmsg), len, mpiR8,  &
                     halo%recvTask(nmsg),              &
                     mpitagHalo + halo%recvTask(nmsg), &
                     halo%communicator, rcvRequest(nmsg), ierr)
   end do

!-----------------------------------------------------------------------
!
!  fill send buffer and post sends
!
!-----------------------------------------------------------------------

   do nmsg=1,halo%numMsgSend
      i=0
      do n=1,halo%sizeSend(nmsg)
         iSrc     = halo%sendAddr(1,n,nmsg)
         jSrc     = halo%sendAddr(2,n,nmsg)
         srcBlock = halo%sendAddr(3,n,nmsg)

         do l=1,nt
         do k=1,nz
            i = i + 1
            bufSend(i,nmsg) = fld(k)%p(iSrc,jSrc,srcBlock)
         end do
         end do
      end do

      do n=i+1,bufSizeSend*nz*nt
         bufSend(n,nmsg) = fill  ! fill remainder of buffer
      end do

      len = halo%SizeSend(nmsg)*nz*nt
      call MPI_ISEND(bufSend(1,nmsg), len, mpiR8, &
                     halo%sendTask(nmsg),             &
                     mpitagHalo + my_task,            &
                     halo%communicator, sndRequest(nmsg), ierr)
   end do
#endif

!-----------------------------------------------------------------------
!
!  while messages are being communicated, fill out halo region
!  needed for masked halos to ensure halo values are filled for
!  halo grid cells that are not updated except in cases where
!  you don't want to overwrite those halos
!
!-----------------------------------------------------------------------

   if (.not. ltripoleOnly) then
      ! tripoleOnly skip fill, do not overwrite any values in interior as they may
      ! already be set and filling tripole is not necessary

      ! fill outer boundary as needed
      ! only fill corners if both edges are being filled
      do iblk = 1, halo%numLocalBlocks
         call get_block_parameter(halo%blockGlobalID(iblk),     &
                                  ilo=ilo,       ihi=ihi,       &
                                  jlo=jlo,       jhi=jhi,       &
                                  iblock=iblock, jblock=jblock)
         if (ewfillouter .or. iblock > 1) then              ! west edge
            do i = 1,nghost
               do k=1,nz
                  fld(k)%p(ilo-i,jlo:jhi,iblk) = fill
               end do
            enddo
         endif
         if (ewfillouter .or. iblock < nblocks_x) then      ! east edge
            do i = 1,nghost
               do k=1,nz
                  fld(k)%p(ihi+i,jlo:jhi,iblk) = fill
               end do
            enddo
         endif
         if (nsfillouter .or. jblock > 1) then              ! south edge
            do j = 1,nghost
               do k=1,nz
                  fld(k)%p(ilo:ihi,jlo-j,iblk) = fill
               end do
            enddo
         endif
         if (nsfillouter .or. jblock < nblocks_y) then      ! north edge
            do j = 1,nghost
               do k=1,nz
                  fld(k)%p(ilo:ihi,jhi+j,iblk) = fill
               end do
            enddo
         endif
         if ((ewfillouter .or. iblock > 1) .and. &          ! southwest corner
             (nsfillouter .or. jblock > 1)) then
            do j = 1,nghost
            do i = 1,nghost
               do k=1,nz
                  fld(k)%p(ilo-i,jlo-j,iblk) = fill
               end do
            enddo
            enddo
         endif
         if ((ewfillouter .or. iblock > 1) .and. &          ! northwest corner
             (nsfillouter .or. jblock < nblocks_y)) then
            do j = 1,nghost
            do i = 1,nghost
               do k=1,nz
                  fld(k)%p(ilo-i,jhi+j,iblk) = fill
               end do
            enddo
            enddo
         endif
         if ((ewfillouter .or. iblock < nblocks_x) .and. &  ! southeast corner
             (nsfillouter .or. jblock > 1)) then
            do j = 1,nghost
            do i = 1,nghost
               do k=1,nz
                  fld(k)%p(ihi+i,jlo-j,iblk) = fill
               end do
            enddo
            enddo
         endif
         if ((ewfillouter .or. iblock < nblocks_x) .and. &  ! northeast corner
             (nsfillouter .or. jblock < nblocks_y)) then
            do j = 1,nghost
            do i = 1,nghost
               do k=1,nz
                  fld(k)%p(ihi+i,jhi+j,iblk) = fill
               end do
            enddo
            enddo
         endif
      enddo ! iblk
   endif ! tripoleonly

!-----------------------------------------------------------------------
!
!  do local copies while waiting for messages to complete
!  if srcBlock is zero, that denotes an eliminated land block or a
!    closed boundary where ghost cell values are undefined
!  if srcBlock is less than zero, the message is a copy out of the
!    tripole buffer and will be treated later
!
!-----------------------------------------------------------------------

   do nmsg=1,halo%numLocalCopies
      iSrc     = halo%srcLocalAddr(1,nmsg)
      jSrc     = halo%srcLocalAddr(2,nmsg)
      srcBlock = halo%srcLocalAddr(3,nmsg)
      iDst     = halo%dstLocalAddr(1,nmsg)
      jDst     = halo%dstLocalAddr(2,nmsg)
      dstBlock = halo%dstLocalAddr(3,nmsg)

      if (srcBlock > 0) then
         if (dstBlock > 0) then
            if (ltripoleOnly) then
               ! skip
            else
               do l=1,nt
               do k=1,nz
                  fld(k)%p(iDst,jDst,dstBlock) = fld(k)%p(iSrc,jSrc,srcBlock)
               end do
               end do
            endif
         else if (dstBlock < 0 .and. ltripole) then ! tripole copy into buffer
            do l=1,nt
            do k=1,nz
               bufTripole(iDst,jDst,k,l) = fld(k)%p(iSrc,jSrc,srcBlock)
            end do
            end do
         endif
      else if (srcBlock == 0) then
         if (ltripoleOnly) then
            ! skip
         else
            do l=1,nt
            do k=1,nz
               fld(k)%p(iDst,jDst,dstBlock) = fill
            end do
            end do
         endif
      endif
   end do

#ifndef NO_MPI
!-----------------------------------------------------------------------
!
!  wait for receives to finish and then unpack the recv buffer into
!  ghost cells
!
!-----------------------------------------------------------------------

   call MPI_WAITALL(halo%numMsgRecv, rcvRequest, rcvStatus, ierr)

   do nmsg=1,halo%numMsgRecv
      i = 0
      do n=1,halo%sizeRecv(nmsg)
         iDst     = halo%recvAddr(1,n,nmsg)
         jDst     = halo%recvAddr(2,n,nmsg)
         dstBlock = halo%recvAddr(3,n,nmsg)

         if (dstBlock > 0) then
            if (ltripoleOnly) then
               ! skip but still need to advance i counter
               i = i + nt*nz
            else
               do l=1,nt
               do k=1,nz
                  i = i + 1
                  fld(k)%p(iDst,jDst,dstBlock) = bufRecv(i,nmsg)
               end do
               end do
            endif
         else if (dstBlock < 0) then !tripole
            if (ltripole) then
               do l=1,nt
               do k=1,nz
                  i = i + 1
                  bufTripole(iDst,jDst,k,l) = bufRecv(i,nmsg)
               end do
               end do
            else
               ! not stored, but still need to advance i counter
               i = i + nt*nz
            endif
         endif
      end do
   end do
#endif

!-----------------------------------------------------------------------
!
! Compute zero_gradient and linear_extrap BCs
! BCs in corner can be computed in either direction first
! Do full length of edges in both directions to address edge box corners, those halo points will be
! computed independently for each box.  Second pass (north/south) will clean global corners
! Needs to come after halo update because want halo to be filled by other methods (cyclic) first
! before applying zero_gradient/linear_extrap in other direction
!
!-----------------------------------------------------------------------

   if (halo%ewBoundaryType == 'zero_gradient' .or. halo%ewBoundaryType == 'linear_extrap' .or. &
       halo%nsBoundaryType == 'zero_gradient' .or. halo%nsBoundaryType == 'linear_extrap') then
      do iblk = 1, halo%numLocalBlocks
         call get_block_parameter(halo%blockGlobalID(iblk),     &
                                  ilo=ilo,       ihi=ihi,       &
                                  jlo=jlo,       jhi=jhi,       &
                                  iblock=iblock, jblock=jblock)

         if (iblock == 1) then                      ! west edge
            if (halo%ewBoundaryType == 'zero_gradient'  ) then
               do j = jlo-nghost,jhi+nghost
               do i = 1,nghost
                  do k=1,nz
                     fld(k)%p(i,j,iblk) = fld(k)%p(ilo,j,iblk)
                  end do
               enddo
               enddo
            elseif (halo%ewBoundaryType == 'linear_extrap'  ) then
               do j = jlo-nghost,jhi+nghost
               do i = 1,nghost
                  do k=1,nz
                     fld(k)%p(i,j,iblk) = fld(k)%p(ilo,j,iblk) - &
                        real((nghost-i+1),dbl_kind)*(fld(k)%p(ilo+1,j,iblk)-fld(k)%p(ilo,j,iblk))
                  end do
               enddo
               enddo
            endif
         endif

         if (iblock == nblocks_x) then              ! east edge
            if (halo%ewBoundaryType == 'zero_gradient'  ) then
               do j = jlo-nghost,jhi+nghost
               do i = 1,nghost
                  do k=1,nz
                     fld(k)%p(ihi+i,j,iblk) = fld(k)%p(ihi,j,iblk)
                  end do
               enddo
               enddo
            elseif (halo%ewBoundaryType == 'linear_extrap') then
               do j = jlo-nghost,jhi+nghost
               do i = 1,nghost
                  do k=1,nz
                     fld(k)%p(ihi+i,j,iblk) = fld(k)%p(ihi,j,iblk) + &
                        real((i),dbl_kind)*(fld(k)%p(ihi,j,iblk)-fld(k)%p(ihi-1,j,iblk))
                  end do
               enddo
               enddo
            endif
         endif

         if (jblock == 1) then                      ! south edge
            if (halo%nsBoundaryType == 'zero_gradient'  ) then
               do j = 1,nghost
               do i = ilo-nghost,ihi+nghost
                  do k=1,nz
                     fld(k)%p(i,j,iblk) = fld(k)%p(i,jlo,iblk)
                  end do
               enddo
               enddo
            elseif (halo%nsBoundaryType == 'linear_extrap'  ) then
               do j = 1,nghost
               do i = ilo-nghost,ihi+nghost
                  do k=1,nz
                     fld(k)%p(i,j,iblk) = fld(k)%p(i,jlo,iblk) - &
                        real((nghost-j+1),dbl_kind)*(fld(k)%p(i,jlo+1,iblk)-fld(k)%p(i,jlo,iblk))
                  end do
               enddo
               enddo
            endif
         endif

         if (jblock == nblocks_y) then              ! north edge
            if (halo%nsBoundaryType == 'zero_gradient'  ) then
               do j = 1,nghost
               do i = ilo-nghost,ihi+nghost
                  do k=1,nz
                     fld(k)%p(i,jhi+j,iblk) = fld(k)%p(i,jhi,iblk)
                  end do
               enddo
               enddo
            elseif (halo%nsBoundaryType == 'linear_extrap') then
               do j = 1,nghost
               do i = ilo-nghost,ihi+nghost
                  do k=1,nz
                     fld(k)%p(i,jhi+j,iblk) = fld(k)%p(i,jhi,iblk) + &
                        real((j),dbl_kind)*(fld(k)%p(i,jhi,iblk)-fld(k)%p(i,jhi-1,iblk))
                  end do
               enddo
               enddo
            endif
         endif

      enddo  ! iblk
   endif  ! zero_gradient or linear_extrap

!-----------------------------------------------------------------------
!
!  take care of northern boundary in tripole case
!  bufTripole array contains the top nghost+1 rows (u-fold) or nghost+2 rows
!  (T-fold) of physical domain for entire (global) top row
!
!-----------------------------------------------------------------------

   if (nxGlobal > 0) then

      do k=1,nz

      select case (fkind(k))
      case (field_type_scalar)
         isign(k) =  1
      case (field_type_vector)
         isign(k) = -1
      case (field_type_angle)
         isign(k) = -1
      case default
         call abort_ice(subname//'ERROR: Unknown field kind')
      end select

      if (halo%tripoleTFlag) then

        select case (floc(k))
        case (field_loc_center)   ! cell center location

           ioffset(k) = -1
           joffset(k) = 0

           !*** top row is degenerate, so must enforce symmetry
           !***   use average of two degenerate points for value

           do l=1,nt
           do i = 2,nxGlobal/2
              iDst = nxGlobal - i + 2
              x1 = bufTripole(i   ,halo%tripoleRows,k,l)
              x2 = bufTripole(iDst,halo%tripoleRows,k,l)
              xavg = (0.5_dbl_kind*(x1 + isign(k)*x2))
              bufTripole(i   ,halo%tripoleRows,k,l) = xavg
              bufTripole(iDst,halo%tripoleRows,k,l) = isign(k)*xavg
           end do
           end do

        case (field_loc_NEcorner)   ! cell corner location

           ioffset(k) = 0
           joffset(k) = 1

        case (field_loc_Eface)   ! cell center location

           ioffset(k) = 0
           joffset(k) = 0

           !*** top row is degenerate, so must enforce symmetry
           !***   use average of two degenerate points for value

           do l=1,nt
           do i = 1,nxGlobal/2
              iDst = nxGlobal + 1 - i
              x1 = bufTripole(i   ,halo%tripoleRows,k,l)
              x2 = bufTripole(iDst,halo%tripoleRows,k,l)
              xavg = (0.5_dbl_kind*(x1 + isign(k)*x2))
              bufTripole(i   ,halo%tripoleRows,k,l) = xavg
              bufTripole(iDst,halo%tripoleRows,k,l) = isign(k)*xavg
           end do
           end do

        case (field_loc_Nface)   ! cell corner (velocity) location

           ioffset(k) = -1
           joffset(k) = 1

        case default
           call abort_ice(subname//'ERROR: Unknown field location')
        end select

      else ! tripole u-fold

        select case (floc(k))
        case (field_loc_center)   ! cell center location

           ioffset(k) = 0
           joffset(k) = 0

        case (field_loc_NEcorner)   ! cell corner location

           ioffset(k) = 1
           joffset(k) = 1

           !*** top row is degenerate, so must enforce symmetry
           !***   use average of two degenerate points for value

           do l=1,nt
           do i = 1,nxGlobal/2 - 1
              iDst = nxGlobal - i
              x1 = bufTripole(i   ,halo%tripoleRows,k,l)
              x2 = bufTripole(iDst,halo%tripoleRows,k,l)
              xavg = (0.5_dbl_kind*(x1 + isign(k)*x2))
              bufTripole(i   ,halo%tripoleRows,k,l) = xavg
              bufTripole(iDst,halo%tripoleRows,k,l) = isign(k)*xavg
           end do
           end do

        case (field_loc_Eface)   ! cell center location

           ioffset(k) = 1
           joffset(k) = 0

        case (field_loc_Nface)   ! cell corner (velocity) location

           ioffset(k) = 0
           joffset(k) = 1

           !*** top row is degenerate, so must enforce symmetry
           !***   use average of two degenerate points for value

           do l=1,nt
           do i = 1,nxGlobal/2
              iDst = nxGlobal + 1 - i
              x1 = bufTripole(i   ,halo%tripoleRows,k,l)
              x2 = bufTripole(iDst,halo%tripoleRows,k,l)
              xavg = (0.5_dbl_kind*(x1 + isign(k)*x2))
              bufTripole(i   ,halo%tripoleRows,k,l) = xavg
              bufTripole(iDst,halo%tripoleRows,k,l) = isign(k)*xavg
           end do
           end do

        case default
           call abort_ice(subname//'ERROR: Unknown field location')
        end select

      endif

      end do ! k

      !*** copy out of global tripole buffer into local
      !*** ghost cells

      !*** look through local copies to find the copy out
      !*** messages (srcBlock < 0)

      do nmsg=1,halo%numLocalCopies
         srcBlock = halo%srcLocalAddr(3,nmsg)

         if (srcBlock < 0) then

            iSrc0    = halo%srcLocalAddr(1,nmsg) ! tripole buffer addr
            jSrc0    = halo%srcLocalAddr(2,nmsg)

            iDst     = halo%dstLocalAddr(1,nmsg) ! local block addr
            jDst     = halo%dstLocalAddr(2,nmsg)
            dstBlock = halo%dstLocalAddr(3,nmsg)

            do k=1,nz

            !*** correct for offsets
            iSrc = iSrc0 - ioffset(k)
            jSrc = jSrc0 - joffset(k)
            if (iSrc < 1       ) iSrc = iSrc + nxGlobal
            if (iSrc > nxGlobal) iSrc = iSrc - nxGlobal

            !*** for center and Eface on u-fold, and NE corner and Nface
            !*** on T-fold, do not need to replace
            !*** top row of physical domain, so jSrc should be
            !*** out of range and skipped
            !*** otherwise do the copy

            if (jSrc <= halo%tripoleRows .and. jSrc>0 .and. jDst>0) then
               do l=1,nt
                  fld(k)%p(iDst,jDst,dstBlock) = isign(k)*bufTripole(iSrc,jSrc,k,l)
               end do
            endif

            end do ! k

         endif
      end do

   endif

#ifndef NO_MPI
!-----------------------------------------------------------------------
!
!  wait for sends to complete and deallocate arrays
!
!-----------------------------------------------------------------------

   call MPI_WAITALL(halo%numMsgSend, sndRequest, sndStatus, ierr)

   deallocate(sndRequest, rcvRequest, sndStatus, rcvStatus, stat=istat)

   if (istat > 0) then
      call abort_ice(subname//'ERROR: deallocating req,status arrays')
      return
   endif

   deallocate(bufSend, bufRecv, stat=istat)

   if (istat > 0) then
      call abort_ice(subname//'ERROR: deallocating send,recv buf arrays')
      return
   endif
#endif

   if (allocated(bufTripole)) then
      deallocate(bufTripole, stat=istat)
      if (istat > 0) then
         call abort_ice(subname//'ERROR: deallocating bufTripole array')
         return
      endif
   endif

!-----------------------------------------------------------------------

!-----------------------------------------------------------------------

   contains

   subroutine add_field(karg, array)

   integer (int_kind), intent(in) :: &
      karg                 ! position of array in the argument list

   real (dbl_kind), dimension(:,:,:), intent(inout), target :: &
      array                ! array to add

   if (size(fieldLoc) < karg .or. size(fieldKind) < karg) then
      call abort_ice(subname//'ERROR: fieldLoc/fieldKind shorter than array list')
      return
   endif

   if (fieldLoc(karg)  == field_loc_unknown .or. &
       fieldKind(karg) == field_type_unknown) then
      call abort_ice(subname//'ERROR: use of field_loc/type_unknown not allowed')
      return
   endif

   if (fieldLoc(karg)  == field_loc_noupdate .or. &
       fieldKind(karg) == field_type_noupdate) return

   nfld = nfld + 1
   fld(nfld)%p => array
   floc(nfld)  = fieldLoc(karg)
   fkind(nfld) = fieldKind(karg)

   end subroutine add_field

 end subroutine ice_HaloUpdate_multi

