   allocate(IARRAY_G(size(ARRAY_G,dim=1),size(ARRAY_G,dim=2)))

   IARRAY_G = 0   ! 0 = false
   where (ARRAY_G) IARRAY_G = 1   ! 1 = true

   if (present(fillValue)) then
      ifillValue = 0
