!  This subroutine scatters a global sized array from src_task to all
!  processors.
!  If grid_ext is true, then ARRAY_G is extended grid and updates outer halo
!  If grid_ext is false, then ARRAY_G is 1:nx_global,1:ny_global and outer
!    halo is updated for cyclic and tripole bcs.
!  If grid_ext is false and interior is true, then only the interior data will 
!    be scattered, no outer halo bcs will be applied

   integer (int_kind), intent(in) :: &
      src_task        ! task from which array should be scattered

   type (distrb), intent(in) :: &
      dst_dist        ! distribution of resulting blocks

   integer (int_kind), dimension(:,:), intent(in) :: &
      ARRAY_G         ! array containing global field on src_task

   integer (int_kind), intent(in), optional :: &
      field_type,    &! id for type of field (scalar, vector, angle)
      field_loc       ! id for location on horizontal grid
                      !  (center, NEcorner, Nface, Eface)

   integer (int_kind), intent(in), optional :: &
      fillValue       ! special value

   logical (log_kind), intent(in), optional :: &
      grid_ext        ! extended grid flag

   integer (int_kind), dimension(:,:,:), intent(inout) :: &
      ARRAY           ! array containing distributed field

!-----------------------------------------------------------------------
!
!  local variables
!
!-----------------------------------------------------------------------

   integer (int_kind) :: &
      i,j,n,         &! dummy loop indices
      ilo,ihi,jlo,jhi,&! block indices
      isrc, jsrc,    &! source addresses
      imin, jmin,    &! min indices for i_glob and j_glob relative to ARRAY_G
      imax, jmax,    &! max indices for i_glob and j_glob relative to ARRAY_G
      xoffset, yoffset,   &! offsets for tripole boundary conditions
      yoffset2,           &!
      isign,              &! sign factor for tripole boundary conditions
      gshift,        &! index shift from ARRAY_G indexing to i_glob, j_glob indexing
                      ! for ext=false, there is no shift, want to scatter 1:nx_global,1:ny_global to same
                      ! for ext=true, there is a shift of nghost, shift 1:nx_global+2*nghost,1:ny_global+2*ghnost 
                      !   to 1-nghost:nx_global+nghost,1-nghost:ny_global+nghost
      dst_block       ! location of block in dst array

   type (block) :: &
      this_block      ! block info for current block

   integer (int_kind) :: &
      lfillValue      ! local special value

   logical (log_kind) :: &
      lext            ! local extended global grid flag

   integer (int_kind), dimension(:,:), allocatable :: &
      LARRAY_G    ! array containing global horizontal field on dst_task
                  ! but with indexing that matches nx_global, ny_global
                  ! to simplify overlapping ext and non-ext coding.
                  ! for non-ext, ARRAY_G and LARRAY_G are (nx_global,ny_global).
                  ! for ext incoming ARRAY_G is (1:nx_global+2*nghost,1:ny_global+2*nghost)
                  ! LARRAY_G is same size, but indexing is
                  !            (1-nghost:nx_global+nghost,1-nghost:ny_global+nghost)
                  ! Could maybe use a pointer but a separate array and copy is more robust

#ifndef SERIAL_REMOVE_MPI
   integer (int_kind) :: &
      nrecvs,        &! actual number of messages received
      ierr            ! MPI error flag

   integer (int_kind), dimension(:), allocatable :: &
      rcv_request     ! request array for receives

   integer (int_kind), dimension(:,:), allocatable :: &
      rcv_status      ! status array for receives

   integer (int_kind), dimension(:,:), allocatable :: &
      msg_buffer      ! buffer for sending blocks
#endif

   character(len=*), parameter :: subname = '(scatter_globalI4)'

   if (present(fillValue)) then
      lfillValue = fillValue
   else
      lfillValue = 0
   endif

   if (present(grid_ext)) then
      lext = grid_ext
   else
      lext = .false.
   endif

   ARRAY = lfillValue

   if (.not.lext) then
      ! may need tripole scatter
      if (.not.present(field_loc) .or. .not.present(field_type)) then
         call abort_ice(subname//'ERROR: grid_ext = false, must pass field_loc and field_type')
      endif

      this_block = get_block(1,1) ! for the tripoleTflag - all blocks have it
      if (this_block%tripoleTFlag) then
         select case (field_loc)
         case (field_loc_center)   ! cell center location
            xoffset = 2
            yoffset = 0
         case (field_loc_NEcorner) ! cell corner (velocity) location
            xoffset = 1
            yoffset = -1
         case (field_loc_Eface)    ! cell face location
            xoffset = 1
            yoffset = 0
         case (field_loc_Nface)    ! cell face location
            xoffset = 2
            yoffset = -1
         case (field_loc_noupdate) ! ghost cells never used - use cell center
            xoffset = 1
            yoffset = 1
         end select
      else
         select case (field_loc)
         case (field_loc_center)   ! cell center location
            xoffset = 1
            yoffset = 1
         case (field_loc_NEcorner) ! cell corner (velocity) location
            xoffset = 0
            yoffset = 0
         case (field_loc_Eface)    ! cell face location
            xoffset = 0
            yoffset = 1
         case (field_loc_Nface)    ! cell face location
            xoffset = 1
            yoffset = 0
         case (field_loc_noupdate) ! ghost cells never used - use cell center
            xoffset = 1
            yoffset = 1
         end select
      endif

      select case (field_type)
      case (field_type_scalar)
         isign =  1
      case (field_type_vector)
         isign = -1
      case (field_type_angle)
         isign = -1
      case (field_type_noupdate) ! ghost cells never used - use cell center
         isign =  1
      case default
         call abort_ice(subname//'ERROR: Unknown field type in scatter')
      end select

   endif ! not lext

!-----------------------------------------------------------------------
!
!  if this task is the src_task, compute updated LARRAY_G which contains
!  outer halo extended grid from ARRAY_G (extended or not), then copy data to
!  message buffer and send to other processors. also copy local blocks
!
!  i_global, j_global are indexed 1-nghost:n*_global+nghost
!
!-----------------------------------------------------------------------

   if (my_task == src_task) then

      allocate(LARRAY_G(1-nghost:nx_global+nghost,1-nghost:ny_global+nghost))

      LARRAY_G = lfillValue
      if (lext) then
         do j = 1-nghost, ny_global+nghost
         do i = 1-nghost, nx_global+nghost
            LARRAY_G(i,j) = ARRAY_G(i+nghost,j+nghost)
         enddo
         enddo
      else
         do j = 1-nghost, ny_global+nghost
            ! tripole
            if (j_global(j) < 0) then
               ! tripole is top block with j_glob < 0
               ! for yoffset=0 or 1, yoffset2=0,0
               ! for yoffset=-1, yoffset2=0,1, for u-rows on T-fold grid
               do yoffset2=0,max(yoffset,0)-yoffset
                  jsrc = ny_global + yoffset + yoffset2 + (j_global(j) + ny_global)
                  do i = 1-nghost, nx_global+nghost
                     if (i_global(i) /= 0) then
                        isrc = nx_global + xoffset - i_global(i)
                        if (isrc < 1) isrc = isrc + nx_global
                        if (isrc > nx_global) isrc = isrc - nx_global
                        LARRAY_G(i,j-yoffset2) = isign * LARRAY_G(isrc,jsrc)
                     endif
                  end do
               end do
            else
               ! copies interior and cyclic
               do i = 1-nghost, nx_global+nghost
                  if (i_global(i) >= 1 .and. i_global(i) <= nx_global .and. &
                      j_global(j) >= 1 .and. j_global(j) <= ny_global) then
                     LARRAY_G(i,j) = ARRAY_G(i_global(i),j_global(j))
                  endif
               enddo
            endif
         enddo
      endif

!tcx
      do j = 1,ny_global
      do i = 1,nx_global
         if (LARRAY_G(i,j) /= ARRAY_G(i,j)) then
            write(6,*) subname,'tcx0 ',i,j,i_global(i),j_global(j)
            write(6,*) subname,'tcx1 ',i,j,ARRAY_G(i,j),LARRAY_G(i,j)
         endif
      enddo
      enddo

      !*** send non-local blocks away

#ifndef SERIAL_REMOVE_MPI
      allocate (msg_buffer(nx_block,ny_block))

      do n=1,nblocks_tot
         if (dst_dist%blockLocation(n) > 0 .and. &
             dst_dist%blockLocation(n)-1 /= my_task) then

            msg_buffer = lfillValue
            this_block = get_block(n,n)
            ilo = this_block%ilo
            ihi = this_block%ihi
            jlo = this_block%jlo
            jhi = this_block%jhi

#if (1 == 1)
            do j=jlo-nghost,jhi+nghost
            do i=ilo-nghost,ihi+nghost
               ! fill entire block
               isrc = this_block%i_glob(ilo) + i - ilo
               jsrc = this_block%j_glob(jlo) + j - jlo
               msg_buffer(i,j) = LARRAY_G(isrc,jsrc)
            enddo
            enddo
#else
            do j=1,ny_block
               if (this_block%jblock == nblocks_y .and. this_block%j_glob(j) < 0) then
                  ! tripole is top block with j_glob < 0
                  ! for yoffset=0 or 1, yoffset2=0,0
                  ! for yoffset=-1, yoffset2=0,1, for u-rows on T-fold grid
                  do yoffset2=0,max(yoffset,0)-yoffset
                     jsrc = ny_global + yoffset + yoffset2 + &
                          (this_block%j_glob(j) + ny_global)
                     do i=1,nx_block
                        if (this_block%i_glob(i) /= 0) then
                           isrc = nx_global + xoffset - this_block%i_glob(i)
                           if (isrc < 1) isrc = isrc + nx_global
                           if (isrc > nx_global) isrc = isrc - nx_global
                           msg_buffer(i,j-yoffset2) = isign * LARRAY_G(isrc,jsrc)
                        endif
                     end do
                  end do
               else
                  ! normal block
                  do i=1,nx_block
                     isrc = this_block%i_glob(i)
                     jsrc = this_block%j_glob(j)
                     if (isrc >=1 .and. isrc <= nx_global .and. &
                         jsrc >=1 .and. jsrc <= ny_global) &
                        msg_buffer(i,j) = LARRAY_G(isrc,jsrc)
                  end do
               endif
            end do
#endif

            call MPI_SEND(msg_buffer, nx_block*ny_block, &
                          MPI_INTEGER, dst_dist%blockLocation(n)-1, 3*mpitag_gs+n, &
                          MPI_COMM_ICE, ierr)

         endif
      end do

      deallocate(msg_buffer)
#endif
      !*** copy any local blocks

      do n=1,nblocks_tot
         if (dst_dist%blockLocation(n) == my_task+1) then
            dst_block = dst_dist%blockLocalID(n)
            this_block = get_block(n,n)
            ilo = this_block%ilo
            ihi = this_block%ihi
            jlo = this_block%jlo
            jhi = this_block%jhi

#if (1 == 1)
            do j=jlo-nghost,jhi+nghost
            do i=ilo-nghost,ihi+nghost
               ! fill entire block
               isrc = this_block%i_glob(ilo) + i - ilo
               jsrc = this_block%j_glob(jlo) + j - jlo
               ARRAY(i,j,dst_block) = LARRAY_G(isrc,jsrc)
            enddo
            enddo
#else
            do j=1,ny_block
               if (this_block%jblock == nblocks_y .and. this_block%j_glob(j) < 0) then
                  ! tripole is top block with j_glob < 0
                  ! for yoffset=0 or 1, yoffset2=0,0
                  ! for yoffset=-1, yoffset2=0,1, for u-rows on T-fold grid
                  do yoffset2=0,max(yoffset,0)-yoffset
                     jsrc = ny_global + yoffset + yoffset2 + &
                         (this_block%j_glob(j) + ny_global)
                     do i=1,nx_block
                        if (this_block%i_glob(i) /= 0) then
                           isrc = nx_global + xoffset - this_block%i_glob(i)
                           if (isrc < 1) isrc = isrc + nx_global
                           if (isrc > nx_global) isrc = isrc - nx_global
                           ARRAY(i,j-yoffset2,dst_block) = isign * LARRAY_G(isrc,jsrc)
                        endif
                     end do
                  end do
               else
                  ! normal block
                  do i=1,nx_block
                     isrc = this_block%i_glob(i)
                     jsrc = this_block%j_glob(j)
                     if (isrc >=1 .and. isrc <= nx_global .and. &
                         jsrc >=1 .and. jsrc <= ny_global) &
                        ARRAY(i,j,dst_block) = LARRAY_G(isrc,jsrc)
                  end do
               endif
            end do
#endif
         endif
      end do

#ifndef SERIAL_REMOVE_MPI
!-----------------------------------------------------------------------
!
!  otherwise receive data from src_task
!
!-----------------------------------------------------------------------

   else

      allocate (rcv_request(nblocks_tot), &
                rcv_status(MPI_STATUS_SIZE, nblocks_tot))

      rcv_request = 0
      rcv_status  = 0

      nrecvs = 0
      do n=1,nblocks_tot
         if (dst_dist%blockLocation(n) == my_task+1) then
            nrecvs = nrecvs + 1
            dst_block = dst_dist%blockLocalID(n)
            call MPI_IRECV(ARRAY(1,1,dst_block), nx_block*ny_block, &
                          MPI_INTEGER, src_task, 3*mpitag_gs+n, &
                          MPI_COMM_ICE, rcv_request(nrecvs), ierr)
         endif
      end do

      if (nrecvs > 0) &
         call MPI_WAITALL(nrecvs, rcv_request, rcv_status, ierr)

      deallocate(rcv_request, rcv_status)
#endif
   endif

!-----------------------------------------------------------------
! Set ghost cell values to 0 for noupdate
!-----------------------------------------------------------------

   if (present(field_loc)) then
   if (field_loc == field_loc_noupdate) then
      do n=1,nblocks_tot
         if (dst_dist%blockLocation(n) == my_task+1 .and. &
             dst_dist%blockLocalID(n) > 0) then

            dst_block = dst_dist%blockLocalID(n)
            this_block = get_block(n,n)
            ! north edge
            do j = this_block%jhi+1,ny_block
            do i = 1, nx_block
               ARRAY (i,j,dst_block) = lfillValue
            enddo
            enddo
            ! east edge
            do j = 1, ny_block
            do i = this_block%ihi+1,nx_block
               ARRAY (i,j,dst_block) = lfillValue
            enddo
            enddo
            ! south edge
            do j = 1, this_block%jlo-1
            do i = 1, nx_block
               ARRAY (i,j,dst_block) = lfillValue
            enddo
            enddo
            ! west edge
            do j = 1, ny_block
            do i = 1, this_block%ilo-1
               ARRAY (i,j,dst_block) = lfillValue
            enddo
            enddo

         endif
      enddo
   endif
   endif

#ifndef SERIAL_REMOVE_MPI
   if (add_mpi_barriers) then
     call ice_barrier()
   endif
#endif

!-----------------------------------------------------------------------

 end subroutine scatter_globalI4

