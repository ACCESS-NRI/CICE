                      !  (center, NEcorner, Nface, Eface)

   logical (log_kind), intent(in), optional :: &
      fillValue       ! special value

   logical (log_kind), intent(in), optional :: &
      grid_ext        ! extended grid flag

   logical (log_kind), dimension(:,:,:), intent(inout) :: &
      ARRAY           ! array containing distributed field

!-----------------------------------------------------------------------
!
!  local variables
!
